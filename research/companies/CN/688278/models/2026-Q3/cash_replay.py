def value(run,r):
    if not run['feasible']:return {'feasible':False,'value':None,'failure':run['failure']}
    rows=run['rows'];pv=sum(z['dps']/(1+r)**z['year'] for z in rows)
    tv=sum(z['dps']/(1+r)**(z['year']-5) for z in rows if z['year']>5)
    return {'feasible':True,'value':pv,'tv5':tv,'dps':[z['dps'] for z in rows[:5]],'r':r,
        'tv5_pv_fraction':tv/(1+r)**5/pv,'final_cash':rows[-1]['cash_close'],
        'capital_return_pv':sum((z['capital_return']+z['exit_distribution'])/run['shares']/(1+r)**z['year'] for z in rows)}

def auxiliary_from_saved(run, saved_aux):
    if not run['feasible'] or len(run['rows']) < 5:
        # Do not expose a partial/failed base as a full Y5 auxiliary valuation.
        out = copy.deepcopy(saved_aux)
        for item in out:
            for key in ('value','tv5','financial_bridge'): item[key] = None
            item['unavailable_reason'] = run.get('failure') or 'Incomplete five-year financial path'
        return out
    b=run['rows'][4]
    excess=sum(b['cash_close'].values())-b['parent_cash_floor']-b['b_cash_floor']-b['r_necessary_cash']
    out=[]
    for old,r in zip(saved_aux,(.115,.10)):
        net=excess/(1+r)**3-b['debt']-1533.266*1.08/(1+.025)+161.65239399/(1+r)**3
        tv=(old['nopat']*old['multiple']+net)/run['shares']
        out.append({'value':sum(z['dps']/(1+r)**z['year'] for z in run['rows'][:5])+tv/(1+r)**5,'tv5':tv,'nopat':old['nopat'],'multiple':old['multiple'],'financial_bridge':net})
    return out
